#!/usr/bin/env node
// Generates a demo project full of FAKE, randomly generated keys: node examples/make-leaky-app.js [dir]
// Keys are assembled at runtime so this repo itself never contains anything that looks like a real secret.
const fs = require("node:fs");
const path = require("node:path");
const dir = path.resolve(process.argv[2] || path.join(require("node:os").tmpdir(), "leaky-app"));
let seed = 42; const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
const AL = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789";
const R = (n, a = AL) => Array.from({ length: n }, () => a[Math.floor(rnd() * a.length)]).join("");
const j = (...p) => p.join("");
const files = {
  "src/ai.ts": `import OpenAI from "openai";\n\n// quick test, will move to env later\nconst openai = new OpenAI({ apiKey: "${j("sk-", "proj-", R(56))}" });\nconst groq = "${j("gs", "k_", R(52))}";\nexport const ok = process.env.OPENAI_API_KEY; // fine\n`,
  "config/db.js": `module.exports = {\n  url: "${j("postgres", "://admin:", R(14), "@db.prism.dev:5432/prod")}",\n  placeholder: "postgres://user:password@localhost/your_db", // ignored\n  stripe: "${j("sk_", "live_", R(24))}",\n};\n`,
  "src/bot.py": `import discord\nTOKEN = "${j("N", R(25), ".", R(6), ".", R(38))}"\naws_secret_access_key = "${R(40, AL + "/+")}"\nAWS_ACCESS_KEY_ID = "${j("AK", "IA", R(16, AL.slice(0, 26) + "0123456789"))}"\n`,
  ".env.example": `OPENAI_API_KEY=sk-your-key-here\nSTRIPE_SECRET=${j("sk_", "live_", "x".repeat(24))}\n`,
  "README.md": "# Leaky app\nEvery key here was randomly generated by prism-secret-scan's demo script. None are real.\n",
};
for (const [f, t] of Object.entries(files)) { fs.mkdirSync(path.dirname(path.join(dir, f)), { recursive: true }); fs.writeFileSync(path.join(dir, f), t); }
console.log(dir);
